const quiz = [];

const levelFor = (category) => category === "emotion" || category === "conversation" ? 2 : 1;

function word(ko, jp, category, note, level = levelFor(category)) {
  quiz.push({
    ko, jp, category, level, format: "word",
    explanation: [{ ko, jp, note }]
  });
}

function phrase(ko, jp, category, parts, level = levelFor(category)) {
  quiz.push({
    ko, jp, category, level, format: "conversation",
    explanation: parts.map(([partKo, partJp, note]) => ({ ko: partKo, jp: partJp, note }))
  });
}

function dialogue(ko, jp, category, parts) {
  quiz.push({
    ko, jp, category, level: 3, format: "conversation",
    explanation: parts.map(([partKo, partJp, note]) => ({ ko: partKo, jp: partJp, note }))
  });
}

function hangul(letter, answer, name, reading, note, level, meaningJa = "") {
  const soundChoices = {
    "ㄱ": "カ／ガ行に近い音 (g/k)", "ㄴ": "ナ行に近い音 (n)", "ㄷ": "タ／ダ行に近い音 (d/t)",
    "ㄹ": "ラ行に近い音 (r/l)", "ㅁ": "マ行に近い音 (m)", "ㅂ": "パ／バ行に近い音 (b/p)",
    "ㅅ": "サ行に近い音 (s)", "ㅇ": "初めは無音／終わりは ng", "ㅈ": "ジャ行に近い音 (j)",
    "ㅊ": "チャ行に近い音 (ch)", "ㅋ": "息を強く出すカ行 (k)", "ㅌ": "息を強く出すタ行 (t)",
    "ㅍ": "息を強く出すパ行 (p)", "ㅎ": "ハ行に近い音 (h)",
    "ㅏ": "ア (a)", "ㅑ": "ヤ (ya)", "ㅓ": "オとアの中間 (eo)", "ㅕ": "ヨとオの中間 (yeo)",
    "ㅗ": "オ (o)", "ㅛ": "ヨ (yo)", "ㅜ": "ウ (u)", "ㅠ": "ユ (yu)", "ㅡ": "ウとイの中間 (eu)",
    "ㅣ": "イ (i)", "ㅐ": "エ (ae)", "ㅔ": "エ (e)",
    "ㄲ": "詰まったカ行 (kk)", "ㄸ": "詰まったタ行 (tt)", "ㅃ": "詰まったパ行 (pp)",
    "ㅆ": "詰まったサ行 (ss)", "ㅉ": "詰まったチャ行 (jj)",
    "ㅒ": "イェ (yae)", "ㅖ": "イェ (ye)", "ㅘ": "ワ (wa)", "ㅙ": "ウェ (wae)",
    "ㅚ": "ウェに近い音 (oe)", "ㅝ": "ウォ (wo)", "ㅞ": "ウェ (we)", "ㅟ": "ウィ (wi)", "ㅢ": "ウイ (ui)",
    "각": "クッ（語末で止める k）", "간": "ンに近い音 (n)", "달": "ルの最後に近い音 (l)",
    "감": "ムに近い音 (m)", "밥": "プッ（唇を閉じる p）", "강": "ング (ng)", "옷": "トッ（語末で止める t）"
  };
  const soundExamples = {
    "ㄱ": "가", "ㄴ": "나", "ㄷ": "다", "ㄹ": "라", "ㅁ": "마", "ㅂ": "바", "ㅅ": "사",
    "ㅇ": "아, 강", "ㅈ": "자", "ㅊ": "차", "ㅋ": "카", "ㅌ": "타", "ㅍ": "파", "ㅎ": "하",
    "ㄲ": "까", "ㄸ": "따", "ㅃ": "빠", "ㅆ": "싸", "ㅉ": "짜"
  };
  quiz.push({
    ko: letter,
    jp: soundChoices[letter] || answer,
    category: "hangul",
    level,
    format: "hangul",
    audioText: name,
    answerAudioText: soundExamples[letter] || name,
    romanization: reading,
    ...(meaningJa ? { meaningJa } : {}),
    explanation: [{ ko: letter, jp: soundChoices[letter] || answer, note }]
  });
}

